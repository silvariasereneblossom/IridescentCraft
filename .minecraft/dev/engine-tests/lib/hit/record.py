#!/usr/bin/env python3
"""Record suites/hit_table.golden.js from the rows the suite `hit-table` prints.

    python .minecraft/dev/engine-tests/lib/hit/record.py            # write the golden file
    python .minecraft/dev/engine-tests/lib/hit/record.py --check    # exit 1 if it would change
    python .minecraft/dev/engine-tests/lib/hit/record.py --check --pack <checkout>/.minecraft   # ... for other scripts

The golden file is the hit table of the handlers that sit, or sat, straight on the Java damage registry, as it was
BEFORE any of them moved onto the shared dispatcher (suites/hit_table.js says what a row is). Record it again only
for a NEW row, or for a behaviour that was changed on purpose with the decision that allows it, and read
`git diff` on the file afterwards: every changed line is a changed damage number.
"""
import json
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TESTS = os.path.normpath(os.path.join(HERE, "..", ".."))
GOLDEN = os.path.join(TESTS, "suites", "hit_table.golden.js")
# Every re-recording that CHANGED rows, with the ruling that allows it: one line each, added in the commit that
# re-records (the golden file's header carries them, so the reason sits next to the numbers)
CHANGES = [
    "ruling 11 (2026-10-14, decision list entry 66): a hit an earlier handler cancelled ends there; the four "
    "broken-weapon rows of Arcane Cleave (no 10 mana), the Samurai and the Berserker (no stamp), and the order row",
    "ruling 12 (2026-10-14, decision list entry 67): the plain-bow effects on the primary hit only; the two splash "
    "rows (no effect on the splash victim, no second heal of Aether's Call)",
    "ruling 13 (2026-10-14, decision list entry 68): no deathskin bonus on a secondary hit; the two secondary rows "
    "on an undead target (10 stays 10, 3 stays 3)",
]
HEAD = """// GENERATED by lib/hit/record.py from the rows suites/hit_table.js prints. Do not edit by hand.
// The hit table of the handlers that sit, or sat, straight on the Java damage registry: [row, what happened].
// A line that changes here is a damage number that changed. See suites/hit_table.js.
// Recorded before any handler moved off the registry (2026-10-13); changed since only on a ruling:
""" + "".join("//   %s\n" % c for c in CHANGES) + """var HT_GOLDEN = [
"""


def main():
    # other arguments go to run.py, in front of its command: `--check --pack <an older checkout>/.minecraft` compares
    # the rows of THOSE scripts with the golden file
    r = subprocess.run([sys.executable, os.path.join(TESTS, "run.py")] + [a for a in sys.argv[1:] if a != "--check"] + ["suite", "hit-table"],
                       capture_output=True, text=True, encoding="utf-8", errors="replace")
    rows = re.findall(r"^\s*ROW (\S+) = (.*)$", r.stdout, re.M)
    if not rows:
        sys.stderr.write(r.stdout[-3000:] + r.stderr[-2000:] + "\nno ROW line: the suite did not get as far as its rows\n")
        return 2
    threw = [n for n, v in rows if v.startswith("THREW")]
    if threw:
        sys.stderr.write("these rows threw, nothing was written: %s\n" % ", ".join(threw))
        return 2
    text = HEAD + ",\n".join("  [%s, %s]" % (json.dumps(n), json.dumps(v.rstrip())) for n, v in rows) + "\n]\n"
    old = open(GOLDEN, encoding="utf-8").read() if os.path.isfile(GOLDEN) else ""
    if "--check" in sys.argv:
        print("hit-table golden: %d rows, %s" % (len(rows), "unchanged" if old == text else "WOULD CHANGE"))
        return 0 if old == text else 1
    with open(GOLDEN, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("hit-table golden: %d rows written%s" % (len(rows), "" if old != text else " (no change)"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
