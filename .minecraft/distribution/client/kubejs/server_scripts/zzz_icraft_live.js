// priority: -1000
// =============================================================================
// Liveness of the server scripts: the ARMED summary line, the FIRED lines once
// a second, and the `/icraft live` command
// File: kubejs/server_scripts/zzz_icraft_live.js (startup_scripts/ and
//       client_scripts/ each have a shorter file of the same name)
// =============================================================================
// The record itself is kept by 00_icraft_guard.js (icraft.live; its header says
// what ARMED and FIRED mean and which lines are printed). This file is the part
// that has to run LAST: when it loads, every script of this type has made its
// registrations, so the one summary line can be printed and compared with the
// expected list (kubejs/config/icraft/live/expected.json, generated by
// dev/loud/gen_liveness.js; the pre-push hook refuses a stale one).
// `// priority: -1000` on line 1 is what makes it last: KubeJS sorts by
// priority and by nothing else, and no other script goes below 0.
//
//   /icraft live            armed and fired counts of the server and startup
//                           scripts, how long ago they loaded, whether anyone
//                           has been online since, and every registration and
//                           feature that has never fired since the load
//   /icraft live <filter>   only names that contain <filter>, or whose script
//                           does (`/icraft live codex`, `/icraft live scaling/`)
//   Operator level 2, and it works from the server console. It reads; it
//   changes nothing. It never prints a player's name.
//
// A comment line of exactly two words is a KubeJS file property: keep such
// lines out of this header.
// =============================================================================

;(function () {
  var TYPE = 'server'
  var TICKS_PER_MINUTE = 1200
  var CHAT_LINES = 30      // a player gets this many lines; the console gets them all
  var CHAT_WIDTH = 900     // and a line is cut at this many characters in chat

  if (typeof icraft === 'undefined' || icraft === null || !icraft.live) {
    console.error('[icraft.live] 00_icraft_guard.js has no icraft.live: liveness is not recorded for the ' + TYPE + ' scripts')
    return
  }
  var live = icraft.live
  var logins = 0           // logins since the scripts loaded: a count, never a name
  var firstTick = -1       // the server's tick count at the first flush after the load

  // FIRED lines: at boot a hundred handlers finish within a second (recipes,
  // loot modifiers, tags, commands), and a first login finishes two dozen.
  // They are collected and printed once a second, one line per event.
  if (typeof global.registerServerTick === 'function') {
    global.registerServerTick('tick_icraftLive', 20, 19, function (event) {
      if (firstTick < 0) firstTick = event.server.tickCount
      live.flush()
    })
    live.batch(true)
  }

  // what fired in the last second before a stop would otherwise never be printed
  ServerEvents.unloaded(icraft.guard('zzz_icraft_live', 'ServerEvents.unloaded', function (event) {
    live.flush()
  }))

  // "never fired" means little for a boot nobody played in: say when the first player came
  PlayerEvents.loggedIn(icraft.guard('zzz_icraft_live', 'PlayerEvents.loggedIn', function (event) {
    logins++
    if (logins === 1) console.log('[icraft.live] PLAYER first login since the ' + TYPE + ' scripts loaded')
  }))

  var describe = function (server, filter) {
    var out = []
    var since = 'the server has not ticked since they loaded'
    var online = 0
    var i = 0
    var j = 0
    var part = null
    var types = ['server', 'startup', 'client']
    var all = global.icraftLiveLines
    if (firstTick >= 0) since = 'loaded ' + Math.floor((server.getTickCount() - firstTick) / TICKS_PER_MINUTE) + ' min ago'
    online = server.getPlayerCount()
    out.push('[icraft live] scripts ' + since + ' (server uptime ' + Math.floor(server.getTickCount() / TICKS_PER_MINUTE) +
      ' min); players: ' + online + ' online now, ' + logins + ' login(s) since the load' +
      (logins === 0 ? ' -- nobody has played: most handlers cannot have fired' : ''))
    for (i = 0; i < types.length; i++) {
      if (!all || typeof all[types[i]] !== 'function') continue
      part = all[types[i]](filter)
      for (j = 0; j < part.length; j++) out.push(part[j])
    }
    return out
  }

  ServerEvents.commandRegistry(icraft.guard('zzz_icraft_live', 'ServerEvents.commandRegistry', function (event) {
    var Commands = event.commands
    var StringArgumentType_live = Java.loadClass('com.mojang.brigadier.arguments.StringArgumentType')
    var run = function (ctx, filter) {
      var text = null
      var toPlayer = false
      var shown = 0
      var i = 0
      var line = ''
      // the command's sender (a CommandSourceStack: a player, or the server console)
      var sender = ctx.source
      var who = null
      try {
        text = describe(sender.getServer(), filter)
        who = sender.getEntity()
        toPlayer = who !== null && who !== undefined
        for (i = 0; i < text.length; i++) {
          line = text[i]
          if (toPlayer) {
            if (shown >= CHAT_LINES) {
              sender.sendSystemMessage(Text.of('  ... ' + (text.length - shown) + ' more line(s): add a filter, or run it from the server console'))
              break
            }
            if (line.length > CHAT_WIDTH) line = line.substring(0, CHAT_WIDTH) + ' ... (cut: add a filter, or use the console)'
          }
          sender.sendSystemMessage(Text.of(line))
          shown++
        }
        return 1
      } catch (e) {
        console.error('[icraft.live] /icraft live failed: ' + e)
        return 0
      }
    }
    event.register(
      Commands.literal('icraft')
        .then(Commands.literal('live')
          .requires(function (src) { return src.hasPermission(2) })
          .executes(function (ctx) { return run(ctx, '') })
          .then(Commands.argument('filter', StringArgumentType_live.greedyString())
            .executes(function (ctx) { return run(ctx, StringArgumentType_live.getString(ctx, 'filter')) })
          )
        )
    )
  }))

  // the other script types hand their part of the report over the shared `global` map
  if (!global.icraftLiveLines) global.icraftLiveLines = {}
  global.icraftLiveLines[TYPE] = live.lines

  // LAST: this file's own registrations are made, so the count is complete
  live.loaded(TYPE)
})()
